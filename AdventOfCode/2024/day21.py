# Keypad Layouts
NUM_KEYPAD = {
    '7': (0, 0), '8': (0, 1), '9': (0, 2),
    '4': (1, 0), '5': (1, 1), '6': (1, 2),
    '1': (2, 0), '2': (2, 1), '3': (2, 2),
                 '0': (3, 1), 'A': (3, 2)
}
NUM_GAP = (3, 0)

DIR_KEYPAD = {
                 '^': (0, 1), 'A': (0, 2),
    '<': (1, 0), 'v': (1, 1), '>': (1, 2)
}
DIR_GAP = (0, 0)

def get_sequences(start_pos, end_pos, gap_pos):
    """
    Returns all shortest valid sequences of moves from start_pos to end_pos
    avoiding the gap_pos.
    """
    sr, sc = start_pos
    er, ec = end_pos
    dr, dc = er - sr, ec - sc
    
    moves = []
    if dr > 0: moves.extend(['v'] * abs(dr))
    elif dr < 0: moves.extend(['^'] * abs(dr))
    if dc > 0: moves.extend(['>'] * abs(dc))
    elif dc < 0: moves.extend(['<'] * abs(dc))
    
    # Simple permutations isn't enough because some might hit the gap.
    # We only care about L-shapes mostly (move all V then all H, or all H then all V).
    # Actually, minimizing turns is usually optimal for the NEXT robot level, 
    # but strictly speaking any shortest Manhattan path is a candidate.
    # However, for these small grids, the only constraints are hitting the gap.
    # Since we want to MINIMIZE the cost at the next level, grouping keys is good (e.g. >>^^ is better than >^>^).
    # So we essentially only consider permutations that don't switch back and forth needlessly.
    # i.e., permutations of the moves list.
    
    from itertools import permutations
    
    valid_seqs = set()
    for p in set(permutations(moves)):
        # Check if hitting gap
        cr, cc = sr, sc
        valid = True
        for move in p:
            if move == '^': cr -= 1
            elif move == 'v': cr += 1
            elif move == '<': cc -= 1
            elif move == '>': cc += 1
            
            if (cr, cc) == gap_pos:
                valid = False
                break
        
        if valid:
            valid_seqs.add("".join(p) + "A")
            
    return list(valid_seqs)

