# Refined Logic
GAP_POS = {
    'num': NUM_GAP,
    'dir': DIR_GAP
}
KEYPADS = {
    'num': NUM_KEYPAD,
    'dir': DIR_KEYPAD
}

@lru_cache(None)
def get_path_cost(start_key, end_key, depth, is_num_pad):
    # Get layout
    keypad = KEYPADS['num'] if is_num_pad else KEYPADS['dir']
    gap = GAP_POS['num'] if is_num_pad else GAP_POS['dir']
    
    start_pos = keypad[start_key]
    end_pos = keypad[end_key]
    
    paths = get_sequences(start_pos, end_pos, gap)
    
    if depth == 0:
        # Base case: I am typing this path.
        # Shortest path is just the length of the shortest permutation.
        # Since permutations are just reorderings, they all have same length.
        return len(paths[0])
    
    # Recursive step
    # We want to minimize the cost of typing 'path' at the NEXT layer (depth-1).
    # Next layer is ALWAYS a DirPad (robots control robots).
    
    best_cost = float('inf')
    for path in paths:
        # Cost of this path is the sum of costs of moving between its chars
        # The robot playing this path starts at 'A'.
        current_cost = 0
        current_key = 'A'
        for char in path:
            current_cost += get_path_cost(current_key, char, depth - 1, False)
            current_key = char
        best_cost = min(best_cost, current_cost)
        
    return best_cost

def solve_code(code, num_robots=2):
    # Code is on NumPad.
    # Layer structure:
    # -1: Me (typing on Robot N's keypad)
    # 0..N-1: Robots (DirPads)
    # N: NumPad (Goal)
    
    # My recursion `depth` definition:
    # `depth` is number of DirPad robots involved in the chain "above" the current keypad.
    
    # For NumPad moves:
    # We generate paths (e.g. "<A"). These are typed on Robot 1's DirPad.
    # Robot 1 is controlled by Robot 2.
    # Robot 2 is controlled by Me.
    # So `depth` for NumPad moves = 2 (Robot 1, Robot 2). The symbols need to go through 2 layers of translation.
    
    # Wait, simple counting:
    # Target: NumPad.
    # Controller 1: DirPad (Robot 1).
    # Controller 2: DirPad (Robot 2).
    # Controller 3: Me.
    
    # Call `get_path_cost(u, v, depth=2, is_num_pad=True)`?
    # If depth=2:
    #   Path on NumPad -> Seq of DirPad chars.
    #   Recursive call `get_path_cost(..., depth=1, is_num_pad=False)`
    #     Path on DirPad -> Seq of DirPad chars.
    #     Recursive call `get_path_cost(..., depth=0, is_num_pad=False)`
    #       Path on DirPad -> I type it. Cost = len.
    
    # Correct. Depth = Number of robots.
    
    total_cost = 0
    current_key = 'A'
    for char in code:
        total_cost += get_path_cost(current_key, char, num_robots, True)
        current_key = char
        
    numeric_part = int(code[:-1].lstrip('0') or '0') # remove 'A', parse int
    return total_cost * numeric_part

